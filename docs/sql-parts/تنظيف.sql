-- ═══════════════════════════════════════════════════════════════════════════
--  HRC — تنظيف مخطط brc للبدء من جديد
--  ---------------------------------------------------------------------------
--  ⚠️⚠️ اقرأ هذا قبل التشغيل — هذا الملف **يحذف**.
--
--  يستخدمه المالك فقط عندما يكون مخطط brc نصف مبنيّ: لصقت جزءاً من السكيما،
--  أو لصقت بياناتي التجريبية بالغلط، وتريد البدء نظيفاً.
--
--  ⛔ ما يحذفه: مخطط brc بالكامل (الجداول والدوال والمشغّلات والأنواع).
--  ✅ ما لا يلمسه إطلاقاً:
--       • public  — مخططك الافتراضي (لا جداول لنا فيه، لكن لا نلمسه)
--       • auth    — المستخدمون وكلمات المرور والحسابات (Supabase يديرها)
--       • storage — الصور والملفات
--       • أي مخطط آخر
--     تحقّقنا من السكيما: كل كائناتها داخل brc، لا واحدة في public أو auth.
--
--  ⚠️ التطبيقات التي تعتمد على brc ستفشل حتى تعيد اللصق. متوقّع.
-- ═══════════════════════════════════════════════════════════════════════════

/* ═══ حاجز أمان ①: هل المشروع فيه بيانات حقيقية؟ ════════════════════════════
   إن كان عدد البطاقات أكثر من ١٠٠، فالأغلب أن هذه بيانات عملك الفعلي —
   وليس أثر لصقة خاطئة. عندها **أوقف** ولا تحذف شيئاً.

   الحل: احذف السطر الذي يرمي الاستثناء فقط إن كنت واثقاً تماماً. */
do $$
declare n int := 0;
begin
  if to_regclass('brc.applicants') is not null then
    execute 'select count(*) from brc.applicants' into n;
  end if;
  if n > 100 then
    raise exception
      '🛑 توقّف: يوجد % بطاقة في brc.applicants — هذه بيانات عمل حقيقية وليست أثر لصقة. الحذف ملغى.', n;
  end if;
end $$;

/* ═══ حاجز أمان ②: هل أنت متأكد؟ ════════════════════════════════════════════
   عطّل الحاجزين فقط إن كنت متأكداً. إن شغّلت الملف كما هو فسيتوقف هنا
   برسالة واضحة — وهذا هو السلوك الصحيح. */
do $$
begin
  if coalesce(current_setting('hrc.force_drop', true), '') <> 'yes' then
    raise exception
      '🛑 الحذف متوقّف. هذا هو السلوك الافتراضي الآمن. لتنفيذ الحذف: شغّل السطر
       set hrc.force_drop = ''yes'';  في بداية الاستعلام، ثم أعد تشغيل الملف.';
  end if;
end $$;

/* ═══ الحذف ═════════════════════════════════════════════════════════════════
   CASCADE يحذف كل ما يعتمد على المخطط: الجداول، الدوال، المشغّلات، الأنواع،
   العروض، السياسات. `if exists` فيمنع الخطأ لو كان المخطط غير موجود أصلاً. */
drop schema if exists brc cascade;

/* ═══ تحقّق ═════════════════════════════════════════════════════════════════
   يجب أن ترى: brc = 0 · public و auth كما كانا. */
select 'جداول brc المتبقية' as العنصر, count(*) as العدد
from pg_tables where schemaname = 'brc'
union all
select 'دوال brc المتبقية', count(*)
from pg_proc p join pg_namespace n on n.oid = p.pronamespace
where n.nspname = 'brc'
union all
select 'جداول public (لم نمسّها)', count(*)
from pg_tables where schemaname = 'public'
union all
select 'حسابات auth.users (سليمة)', count(*) from auth.users
order by 1;
