--  HRC — تشخيص: هل بقي شيء معلّق من محاولة سابقة؟
--  ---------------------------------------------------------------------------
--  ⚠️ شغّل كل استعلام **على حدة** (ظلّل واحداً ← Run ← ثم التالي).
--     السبب: لو كان pg_cron غير مفعّلة، استعلامها يفشل — ولن نريد أن يُفشل
--     الباقي معه.
-- ═══════════════════════════════════════════════════════════════════════════ */

/* ═══ ① معاملات مفتوحة ═══════════════════════════════════════════════════════
   لو لصقت `BEGIN;` ولم تلصق `COMMIT;` تبقى معاملة مفتوحة تقفل الجداول، فتفشل
   كل لصقة بعدها برسالة غير مفهومة.

   ✅ المطلوب: صفر صفوف.
   ❌ أي صف = مشكلة. الحل في نهاية هذا الملف. */
select pid, state, now() - xact_start as المدة, left(query, 60) as الاستعلام
from pg_stat_activity
where datname = current_database() and state = 'idle in transaction'
order by xact_start;

/* ─────────────────────────────────────────────────────────────────────────
   ═══ ② أقفال غير ممنوحة — استعلام منفصل ═══
   ✅ صفر صفوف = لا شيء مقفل.
   ───────────────────────────────────────────────────────────────────────── */
select l.pid, c.relname as الجدول, l.mode as نوع_القفل
from pg_locks l
join pg_class c on c.oid = l.relation
join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'brc' and not l.granted;

/* ─────────────────────────────────────────────────────────────────────────
   ═══ ③ بقايا في public — استعلام منفصل ═══
   هل بقيت جداول في `public` من محاولة لصق أقدم؟ سكيما قديمة كانت تنشئ هناك.
   ✅ صفر صفوف = لا بقايا. أي صف = أثر من محاولة سابقة (أرسله لي).
   ───────────────────────────────────────────────────────────────────────── */
select table_name as جدول_في_public
from information_schema.tables
where table_schema = 'public' and table_type = 'BASE TABLE'
order by 1;

/* ─────────────────────────────────────────────────────────────────────────
   ═══ ④ الإضافات — استعلام منفصل ═══
   pgcrypto و pg_cron يجب أن تكونا موجودتين.
   ───────────────────────────────────────────────────────────────────────── */
select extname as الإضافة, extversion as الإصدار
from pg_extension
order by 1;

/* ─────────────────────────────────────────────────────────────────────────
   ═══ ⑤ المهام المجدولة — استعلام منفصل ═══
   الكاملة = ٤ مهام.
   ❌ إن قال `relation cron.job does not exist` فـpg_cron غير مفعّلة:
      Database → Extensions → فعّل pg_cron ثم أعد الجزء 1 من السكيما.
   ───────────────────────────────────────────────────────────────────────── */
select jobname as المهمة, schedule as التوقيت, active as مفعّلة
from cron.job
order by 1;

