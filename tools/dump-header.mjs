/* ═══════════════════════════════════════════════════════════════════════════
   HRC — قراءة أعداد الترويسة من ملف الاسترجاع الكامل
   ---------------------------------------------------------------------------
   لماذا وحدة مستقلة: مولّد الموقع يكتب في أعلى كل ملف سطراً مثل
       --  الأعداد : 3 staff · 726 applicants · 22 jobs · …
       --            عدّاد البطاقات: 176
   فإذا نُزّلت نسخة أحدث من صفحة النسخ الاحتياطي تغيّرت الأعداد، ولا يصحّ
   أن يبقى التحقّق مثبّتاً على أرقام نسخة قديمة (فيبدو النجاح فشلاً).
   هذا الملف يقرأ الأعداد من الملف نفسه — مصدر واحد للأداة وللفحوص.
   ═══════════════════════════════════════════════════════════════════════════ */

/* حدود الفاصلة في الترويسة هي «·» (U+00B7) كما يكتبها المولّد */
export function headerCounts(text) {
  const out = {};
  const line = /^--\s*الأعداد\s*:\s*(.+)$/m.exec(text);
  if (line) {
    for (const part of line[1].split('·')) {
      const m = /^\s*(\d+)\s+([a-z_]+)\s*$/.exec(part);
      if (m) out[m[2]] = Number(m[1]);
    }
  }
  const counter = /^--\s*عدّاد البطاقات\s*:\s*(\d+)/m.exec(text);
  if (counter) out.counter = Number(counter[1]);
  return Object.keys(out).length ? out : null;
}
